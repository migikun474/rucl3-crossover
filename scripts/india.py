"""India hardware mapping: what a machine must have at the crossover, against
the National Quantum Mission (NQM) target and the QpiAI-Indus system.

    python scripts/india.py

For each parameter set, physical error rate and surface-code layout
(time-optimal: as many magic-state factories as speed up the run;
qubit-minimal: one factory) the crossover is recomputed, because the slower
qubit-minimal layout also moves N*.  Gap factors are needed / available.
Writes data/india.json and paper/india_numbers.tex.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

import rucl3  # noqa: E402,F401
import numpy as np  # noqa: E402
from rucl3.analysis.crossover import (NQM_QUBITS, QPIAI_TWO_QUBIT_FIDELITY,  # noqa: E402
                                      crossover)
from rucl3.analysis.fits import fit_classical, fit_trotter, read_jsonl  # noqa: E402
from rucl3.model import params as P  # noqa: E402
from rucl3.target import DEFAULT  # noqa: E402

from crossover import inelastic_peak  # noqa: E402

DATA = ROOT / "data"
YEAR = 3.156e7
SETS = ["winter2017", "ran2017", "laurell2020"]
LAYOUTS = {"fast": None, "min": {"maxTFactories": 1}}
QPIAI_QUBITS = 25
THRESHOLD = 1e-2  # surface-code threshold, order of magnitude


def main():
    rows = []
    target = DEFAULT
    for params in SETS:
        p = P.get(params)
        cfit = fit_classical([r for r in read_jsonl(DATA / "exact_runs.jsonl")
                              if r["params"] == params])
        scan = [r for r in read_jsonl(DATA / "trotter_scan.jsonl") if r["params"] == params]
        spec = fit_trotter(scan, 2, conservative=True).spec
        S_peak, _ = inelastic_peak(DATA, params, target.dE)
        for perr in (1e-3, 1e-4):
            for layout, cons in LAYOUTS.items():
                res = crossover(p, target, spec, cfit, S_peak, range(16, 121, 2), perr,
                                constraints=cons)
                Ns = res.N_star
                i = list(res.N).index(Ns) if Ns else None
                q = int(res.physical_qubits[i]) if Ns else None
                rows.append({"params": params, "p": perr, "layout": layout, "N_star": Ns,
                             "qubits": q, "runtime_yr": res.quantum_s[i] / YEAR if Ns else None})
                print(rows[-1], flush=True)
    (DATA / "india.json").write_text(json.dumps(rows, indent=1))

    def sel(**kw):
        return [r for r in rows if all(r[k] == v for k, v in kw.items()) and r["qubits"]]

    m = {}
    for perr, tag in ((1e-4, "B"), (1e-3, "A")):
        for layout, word in (("fast", "Fast"), ("min", "Min")):
            rs = sel(p=perr, layout=layout)
            qs = [r["qubits"] for r in rs]
            ns = [r["N_star"] for r in rs]
            ts = [r["runtime_yr"] for r in rs]
            m[f"india{word}Qlo{tag}"] = f"{min(qs) / 1e3:.0f}"
            m[f"india{word}Qhi{tag}"] = f"{max(qs) / 1e3:.0f}"
            m[f"india{word}Nlo{tag}"] = str(min(ns))
            m[f"india{word}Nhi{tag}"] = str(max(ns))
            m[f"india{word}Tlo{tag}"] = f"{min(ts):.0f}"
            m[f"india{word}Thi{tag}"] = f"{max(ts):.0f}"
            m[f"india{word}GapNQMlo{tag}"] = f"{min(qs) / NQM_QUBITS[1]:.0f}"
            m[f"india{word}GapNQMhi{tag}"] = f"{max(qs) / NQM_QUBITS[1]:.0f}"
            m[f"india{word}Doublo{tag}"] = f"{np.log2(min(qs) / NQM_QUBITS[1]):.0f}"
            m[f"india{word}Doubhi{tag}"] = f"{np.log2(max(qs) / NQM_QUBITS[1]):.0f}"
    qp = 1 - QPIAI_TWO_QUBIT_FIDELITY
    m["indiaQpiaiErrPct"] = f"{100 * qp:.0f}"
    m["indiaQpiaiOverThreshold"] = f"{qp / THRESHOLD:.0f}"
    m["indiaErrGapA"] = f"{qp / 1e-3:.0f}"
    m["indiaErrGapB"] = f"{qp / 1e-4:.0f}"
    m["indiaQpiaiQubits"] = str(QPIAI_QUBITS)
    with open(ROOT / "paper" / "india_numbers.tex", "w") as f:
        f.write("% generated by scripts/india.py -- do not edit by hand\n")
        for k, v in m.items():
            f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    for k, v in m.items():
        print(k, v)


if __name__ == "__main__":
    main()
